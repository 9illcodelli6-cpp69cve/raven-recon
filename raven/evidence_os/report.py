"""RAVEN V7 Report Engine — Part 10.

Generates structured security research reports from findings and evidence.
All reports are advisory and clearly mark findings as unverified candidates.
"""
from __future__ import annotations

import time
import uuid
from dataclasses import dataclass, field
from enum import Enum
from typing import List, Optional


class ReportFormat(str, Enum):
    MARKDOWN = "markdown"
    JSON     = "json"
    TEXT     = "text"


@dataclass
class ReportSection:
    heading: str
    body:    str
    kind:    str = "general"   # general | finding | evidence | summary


@dataclass
class ReportOutput:
    report_id:    str = field(default_factory=lambda: uuid.uuid4().hex[:16])
    title:        str = ""
    workspace_id: str = "default"
    format:       ReportFormat = ReportFormat.MARKDOWN
    sections:     List[ReportSection] = field(default_factory=list)
    created_at:   int = field(default_factory=lambda: int(time.time() * 1000))
    is_advisory:  bool = True   # INVARIANT: always True

    def __post_init__(self):
        object.__setattr__(self, "is_advisory", True)

    def __setattr__(self, name: str, value):
        if name == "is_advisory" and "is_advisory" in self.__dict__:
            raise AttributeError("is_advisory is immutable — reports are always advisory")
        object.__setattr__(self, name, value)

    def render(self) -> str:
        if self.format == ReportFormat.MARKDOWN:
            return self._render_markdown()
        elif self.format == ReportFormat.JSON:
            return self._render_json()
        else:
            return self._render_text()

    def _render_markdown(self) -> str:
        lines = [
            f"# {self.title}",
            "",
            "> **ADVISORY**: All findings are candidate observations requiring human verification.",
            "> No finding in this report constitutes a confirmed vulnerability.",
            "",
        ]
        for s in self.sections:
            lines.append(f"## {s.heading}")
            lines.append(s.body)
            lines.append("")
        return "\n".join(lines)

    def _render_text(self) -> str:
        lines = [
            self.title,
            "=" * len(self.title),
            "ADVISORY: All findings require human verification.",
            "",
        ]
        for s in self.sections:
            lines.append(f"--- {s.heading} ---")
            lines.append(s.body)
            lines.append("")
        return "\n".join(lines)

    def _render_json(self) -> str:
        import json
        return json.dumps({
            "report_id": self.report_id,
            "title": self.title,
            "is_advisory": True,
            "sections": [
                {"heading": s.heading, "body": s.body, "kind": s.kind}
                for s in self.sections
            ],
        }, indent=2)


class ReportEngine:
    """Generates advisory security research reports."""

    def __init__(self):
        self._reports: dict[str, ReportOutput] = {}

    def generate_from_findings(
        self,
        findings: List[dict],
        title: str = "Security Research Report",
        workspace_id: str = "default",
        fmt: ReportFormat = ReportFormat.MARKDOWN,
    ) -> ReportOutput:
        sections = [
            ReportSection(
                heading="Executive Summary",
                body=(
                    f"This report summarizes {len(findings)} candidate finding(s) "
                    "identified during automated reconnaissance. "
                    "ALL items require human verification before any action is taken."
                ),
                kind="summary",
            )
        ]

        for i, f in enumerate(findings, 1):
            fid    = f.get("finding_id", f"F{i}")
            cat    = f.get("category", "UNKNOWN")
            title_ = f.get("title", f"Candidate Finding {i}")
            body   = f.get("description", "No description provided.")
            sections.append(ReportSection(
                heading=f"[CANDIDATE] {title_} ({cat})",
                body=(
                    f"**Finding ID**: {fid}\n"
                    f"**Category**: {cat}\n"
                    f"**Status**: Unverified candidate — human review required\n\n"
                    f"{body}"
                ),
                kind="finding",
            ))

        sections.append(ReportSection(
            heading="Disclaimer",
            body=(
                "This report was generated by RAVEN V7. "
                "All findings are AI-assisted observations (advisory). "
                "RAVEN does not confirm vulnerabilities. "
                "A security professional must verify each item against "
                "the defined program scope and rules of engagement."
            ),
            kind="general",
        ))

        report = ReportOutput(
            title=title,
            workspace_id=workspace_id,
            format=fmt,
            sections=sections,
        )
        self._reports[report.report_id] = report
        return report

    def get(self, report_id: str) -> Optional[ReportOutput]:
        return self._reports.get(report_id)

    def list_all(self, workspace_id: str = None) -> List[ReportOutput]:
        if workspace_id:
            return [r for r in self._reports.values() if r.workspace_id == workspace_id]
        return list(self._reports.values())

    def count(self) -> int:
        return len(self._reports)
